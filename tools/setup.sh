#!/usr/bin/env bash
# Fetch the pinned dependencies of dotbench and write .dotbench-env.
#
#   usage: tools/setup.sh [DEPS_DIR]      (default: <repo>/.deps, git-ignored)
#
# Nothing here is modified afterwards: the SDK, KodeOS and LVGL trees are read-only inputs.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPS="${1:-$ROOT/.deps}"

KODE_SDK_COMMIT=c9568a3331363cb8dd8e549c8f0ba35dc3cf8dd5
KODEOS_COMMIT=7612a16
LVGL_TAG=v9.6.0
EMSDK_VERSION=7.0.0

mkdir -p "$DEPS/third"

fetch_commit() {   # dir url commit-or-tag
    local dir="$1" url="$2" ref="$3"
    if [ -d "$dir/.git" ]; then
        echo "have $dir"
        return
    fi
    git init -q "$dir"
    git -C "$dir" remote add origin "$url"
    # A full SHA can be fetched directly; an abbreviated one needs history.
    if ! git -C "$dir" fetch -q --depth 1 origin "$ref" 2>/dev/null; then
        git -C "$dir" fetch -q origin
        git -C "$dir" checkout -q "$ref"
    else
        git -C "$dir" checkout -q FETCH_HEAD
    fi
    echo "fetched $dir at $(git -C "$dir" rev-parse --short HEAD)"
}

fetch_commit "$DEPS/kode-sdk"      https://github.com/kodediy/kode-sdk.git  "$KODE_SDK_COMMIT"
fetch_commit "$DEPS/KodeOS"        https://github.com/kodediy/KodeOS.git    "$KODEOS_COMMIT"
fetch_commit "$DEPS/third/lvgl"    https://github.com/lvgl/lvgl.git         "$LVGL_TAG"

if [ ! -x "$DEPS/emsdk/emsdk" ]; then
    git clone -q --depth 1 https://github.com/emscripten-core/emsdk.git "$DEPS/emsdk"
fi
"$DEPS/emsdk/emsdk" install "$EMSDK_VERSION" >/dev/null
"$DEPS/emsdk/emsdk" activate "$EMSDK_VERSION" >/dev/null

cat > "$ROOT/.dotbench-env" <<EOF
# generated by tools/setup.sh; source it in each shell
export DOTBENCH_SDK="$DEPS/kode-sdk"
export DOTBENCH_LVGL="$DEPS/third/lvgl"
export DOTBENCH_EMSDK="$DEPS/emsdk"
export DOTBENCH_KODEOS="$DEPS/KodeOS"
EOF

echo
echo "Done. Next:"
echo "  source .dotbench-env"
echo "  tools/dotbench sdk"
echo "  tests/node/run.sh"
