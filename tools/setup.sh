#!/usr/bin/env bash
# Fetch the pinned dependencies of dotbench and write .dotbench-env.
#
#   usage: tools/setup.sh [DEPS_DIR]      (default: <repo>/.deps, git-ignored)
#
# Nothing here is modified afterwards: the SDK, KodeOS and LVGL trees are read-only inputs.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEPS="${1:-$ROOT/.deps}"

# the pins live in tools/pins.env (tools/upstream-update.sh moves them)
set -a; . "$ROOT/tools/pins.env"; set +a

mkdir -p "$DEPS/third"

fetch_commit() {   # dir url ref [expected-full-sha]   (ref: tag or commit)
    local dir="$1" url="$2" ref="$3" want="${4:-}"
    if [ -d "$dir/.git" ]; then
        echo "have $dir at $(git -C "$dir" rev-parse --short HEAD)"
    else
        git init -q "$dir"
        git -C "$dir" remote add origin "$url"
        # A tag or a full SHA can be fetched directly; an abbreviated SHA needs history.
        if ! git -C "$dir" fetch -q --depth 1 origin "$ref" 2>/dev/null; then
            git -C "$dir" fetch -q origin
            git -C "$dir" checkout -q "$ref"
        else
            git -C "$dir" checkout -q FETCH_HEAD
        fi
        echo "fetched $dir at $(git -C "$dir" rev-parse --short HEAD)"
    fi
    if [ -n "$want" ] && [ "$(git -C "$dir" rev-parse HEAD)" != "$want" ]; then
        echo "setup: $dir is at $(git -C "$dir" rev-parse HEAD), the pin says $want (a moved tag, or a stale $dir: delete it)" >&2
        exit 1
    fi
}

fetch_commit "$DEPS/kode-sdk"           https://github.com/kodediy/kode-sdk.git           "$KODE_SDK_TAG" "$KODE_SDK_COMMIT"
fetch_commit "$DEPS/KodeOS"             https://github.com/kodediy/KodeOS.git             "$KODEOS_TAG"   "$KODEOS_COMMIT"
fetch_commit "$DEPS/kode-app-kody_kart" https://github.com/kodediy/kode-app-kody_kart.git "$KODY_KART_COMMIT" "$KODY_KART_COMMIT"
fetch_commit "$DEPS/third/lvgl"         https://github.com/lvgl/lvgl.git                  "$LVGL_TAG"

# DOTBENCH_EMSDK_REUSE=<dir>: use an Emscripten SDK that is already installed there (it must be $EMSDK_VERSION) instead of
# installing one under $DEPS (the install is about 1 GB; CI caches it with actions/cache).
EMSDK_DIR="$DEPS/emsdk"
if [ -n "${DOTBENCH_EMSDK_REUSE:-}" ]; then
    EMSDK_DIR="$DOTBENCH_EMSDK_REUSE"
    have="$(tr -d '"\n' < "$EMSDK_DIR/upstream/emscripten/emscripten-version.txt" 2>/dev/null || true)"
    [ "$have" = "$EMSDK_VERSION" ] || { echo "setup: $EMSDK_DIR has Emscripten '$have', the pin is $EMSDK_VERSION" >&2; exit 1; }
    echo "reusing Emscripten $have at $EMSDK_DIR"
else
    if [ ! -x "$EMSDK_DIR/emsdk" ]; then
        git clone -q --depth 1 https://github.com/emscripten-core/emsdk.git "$EMSDK_DIR"
    fi
    "$EMSDK_DIR/emsdk" install "$EMSDK_VERSION" >/dev/null
    "$EMSDK_DIR/emsdk" activate "$EMSDK_VERSION" >/dev/null
fi

cat > "$ROOT/.dotbench-env" <<EOF
# generated by tools/setup.sh; source it in each shell
export DOTBENCH_SDK="$DEPS/kode-sdk"
export DOTBENCH_LVGL="$DEPS/third/lvgl"
export DOTBENCH_EMSDK="$EMSDK_DIR"
export DOTBENCH_KODEOS="$DEPS/KodeOS"
export DOTBENCH_DEPS="$DEPS"
EOF

echo
echo "Done. Next:"
echo "  source .dotbench-env"
echo "  tools/dotbench sdk"
echo "  tests/node/run.sh"
