#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
// templates/component-starter/manifest.schema.json is the one source of the manifest schema. This copies it to
// runtime/web-adapter/dotpart-schema.js (what the browser validates with) and into section 5 of the three PROMPT files.
// usage: node tools/dblib/part/gen-schema.mjs [--check]     (--check exits 1 when a copy is stale; used by the tests)
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./build.mjs";

const T = path.join(ROOT, "templates/component-starter");
const text = fs.readFileSync(path.join(T, "manifest.schema.json"), "utf8").trimEnd();
JSON.parse(text);
const js = `// SPDX-License-Identifier: GPL-3.0-or-later\n// GENERATED by tools/dblib/part/gen-schema.mjs from templates/component-starter/manifest.schema.json. Do not edit.\nexport default ${text};\n`;
const targets = [[path.join(ROOT, "runtime/web-adapter/dotpart-schema.js"), () => js]];
for (const f of ["PROMPT.md", "PROMPT.pt-BR.md", "PROMPT.es.md"]) {
  targets.push([path.join(T, f), (cur) => {
    const a = cur.indexOf("## 5. manifest.schema.json (complete)"), fence = cur.indexOf("```json\n", a) + 8, end = cur.indexOf("\n```\n", fence);
    if (a < 0 || fence < 8 || end < 0) throw new Error(f + ": section 5 not found");
    return cur.slice(0, fence) + text + cur.slice(end);
  }]);
}
let stale = 0;
for (const [file, make] of targets) {
  const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "", next = make(cur);
  if (cur !== next) { stale++; if (process.argv.includes("--check")) console.error("stale: " + path.relative(ROOT, file)); else { fs.writeFileSync(file, next); console.log("updated " + path.relative(ROOT, file)); } }
}
if (process.argv.includes("--check") && stale) process.exit(1);
if (!stale) console.log("schema copies are current");
