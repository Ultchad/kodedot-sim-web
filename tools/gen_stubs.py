#!/usr/bin/env python3
"""Generate one stub .c file per SDK khal/kdrv header.

Policy (c) of dotbench: every function a header declares that no compiled object
defines gets a stub that logs "dotbench: <function> not implemented" once and
returns the SDK's failure value. Symbols already defined by a real or fake
object (read with `nm`) are skipped, so a stub never collides with real code.

usage: gen_stubs.py --sdk DIR --defined FILE --out DIR [--include-root DIR ...]
  --defined  text file with one defined symbol per line (output of `nm -g --defined-only`)
"""
import argparse
import pathlib
import re
import sys

KEYWORDS = {"if", "while", "for", "switch", "return", "sizeof", "defined"}


def strip_comments(s):
    s = re.sub(r"/\*.*?\*/", " ", s, flags=re.S)
    s = re.sub(r"//[^\n]*", " ", s)
    return s


def strip_preproc(s):
    out = []
    cont = False
    for line in s.split("\n"):
        if cont or line.lstrip().startswith("#"):
            cont = line.rstrip().endswith("\\")
            continue
        out.append(line)
    return "\n".join(out)


def statements(s):
    """Split on ';' and '}' at brace depth 0; skip everything inside braces."""
    depth = 0
    cur = []
    for ch in s:
        if ch == "{":
            depth += 1
            continue
        if ch == "}":
            if depth == 0:
                continue          # the closing brace of extern "C" {
            depth -= 1
            if depth == 0:
                cur.append(" {} ")
            continue
        if depth:
            continue
        if ch == ";":
            yield "".join(cur).strip()
            cur = []
        else:
            cur.append(ch)
    tail = "".join(cur).strip()
    if tail:
        yield tail


DECL = re.compile(
    r"^(?P<ret>[A-Za-z_][\w\s\*]*?)\s*\b(?P<name>[A-Za-z_]\w*)\s*\((?P<args>.*)\)\s*(?P<attr>(__attribute__\s*\(\(.*\)\))?)\s*$",
    re.S)


def preprocess(path, cpp_flags):
    """Run the C preprocessor over a header and keep only the lines that come from
    that header itself (so #if CONFIG_x blocks are resolved against the real config)."""
    import shlex
    import subprocess
    r = subprocess.run(["emcc", "-E", "-x", "c", str(path)] + shlex.split(cpp_flags),
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write("gen_stubs: cannot preprocess %s:\n%s\n" % (path, r.stderr[-800:]))
        return path.read_text(errors="replace")
    keep, out = False, []
    target = str(path)
    for line in r.stdout.split("\n"):
        if line.startswith("# "):
            m = re.match(r'# \d+ "([^"]*)"', line)
            if m:
                keep = (m.group(1) == target) or pathlib.Path(m.group(1)).resolve() == path.resolve()
            continue
        if keep:
            out.append(line)
    return "\n".join(out)


def parse_header(path, cpp_flags=None):
    raw = preprocess(path, cpp_flags) if cpp_flags is not None else path.read_text(errors="replace")
    text = strip_preproc(strip_comments(raw))
    text = re.sub(r'extern\s+"C"\s*\{', " ", text)
    funcs = []
    for st in statements(text):
        st = " ".join(st.split())
        if not st or st.startswith("typedef") or "(*" in st.split("(")[0]:
            continue
        if st.startswith(("static", "_Static_assert", "struct ", "enum ", "union ")) and "(" not in st:
            continue
        if "{}" in st:
            continue
        m = DECL.match(st)
        if not m:
            continue
        ret = m.group("ret").strip()
        name = m.group("name")
        if name in KEYWORDS or ret.startswith("static") or ret.startswith("extern"):
            ret = ret.replace("extern", "").strip()
            if ret.startswith("static"):
                continue
        if not ret:
            continue
        funcs.append((ret, name, m.group("args").strip(), m.group("attr")))
    return funcs


def fail_value(ret, attr):
    r = ret.replace("const", "").strip()
    if "noreturn" in (attr or ""):
        return "abort"
    if r == "void":
        return None
    if "*" in r:
        return "NULL"
    if r == "kode_status_t":
        return "KODE_ERROR"
    if r == "esp_err_t":
        return "ESP_ERR_NOT_SUPPORTED"
    if r == "bool":
        return "false"
    if re.fullmatch(r"(unsigned |signed )?(char|short|int|long)( long)?|u?int(8|16|32|64)_t|size_t|ssize_t|float|double|uintptr_t", r):
        return "0"
    return "ZERO:" + r  # enums, structs: a zeroed static of that type


def emit(header, funcs, defined):
    lines = [
        "/* Generated by tools/gen_stubs.py from %s. Do not edit. */" % header,
        '#include "%s"' % header,
        '#include "dotbench_stub.h"',
        "",
    ]
    n = 0
    for ret, name, args, attr in funcs:
        if name in defined:
            continue
        fv = fail_value(ret, attr)
        decl_args = args if args else "void"
        sig = "%s %s(%s)" % (ret, name, decl_args)
        body = ["    DOTBENCH_UNIMPLEMENTED(%s);" % name]
        if fv == "abort":
            body.append("    abort();")
        elif fv is None:
            pass
        elif fv.startswith("ZERO:"):
            body.append("    %s z; memset(&z, 0, sizeof z); return z;" % fv[5:])
        else:
            body.append("    return %s;" % fv)
        lines.append("%s\n{\n%s\n}\n" % (sig, "\n".join(body)))
        n += 1
    return "\n".join(lines), n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", required=True)
    ap.add_argument("--defined", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cpp-flags", default=None, help="flags for the preprocessor run over each header")
    ap.add_argument("--glob", action="append",
                    default=["components/khal/*/include/*.h", "components/kdrv/*/include/*.h",
                             "components/khal/*/src/*_port.h"])
    a = ap.parse_args()
    sdk = pathlib.Path(a.sdk)
    defined = set(pathlib.Path(a.defined).read_text().split())
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    total = 0
    written = set()
    for g in a.glob:
        for h in sorted(sdk.glob(g)):
            funcs = parse_header(h, a.cpp_flags)
            src, n = emit(h.name, funcs, defined)
            f = out / (h.stem + ".c")
            if n == 0:
                if f.exists():
                    f.unlink()
                continue
            if not f.exists() or f.read_text() != src:
                f.write_text(src)
            written.add(f.name)
            total += n
    for f in out.glob("*.c"):
        if f.name not in written and f.name != "stub_support.c":
            f.unlink()
    print("gen_stubs: %d stub functions in %d files" % (total, len(written)))


if __name__ == "__main__":
    sys.exit(main())
