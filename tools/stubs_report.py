#!/usr/bin/env python3
"""List the generated-stub functions a linked firmware really references, from its linker map.

  stubs_report.py kodeos.map [--minus buttons_led.map --minus display_lvgl.map] [--json out.json]

A stub is a symbol defined by an object of libdotbench_stubs.a (generated by gen_stubs.py, one object per
khal/kdrv header). Output groups them by that object (= by hardware area). With --minus the functions
that the other maps also reference are removed: the work list "stubbed, referenced by kodeOS, not by an app".
Hand-written stubs (runtime/drivers/kodeos_boot/internal_stubs.c) are listed under their own heading.
"""
import argparse
import collections
import json
import re
import sys

PAT = re.compile(r"\((?P<obj>[^()]+\.o)\):\((?P<sym>[A-Za-z_][\w.$]*)\)\s*$")


def stub_refs(path):
    refs = collections.defaultdict(set)
    for line in open(path, errors="replace"):
        m = PAT.search(line)
        if not m:
            continue
        lib = line[:m.start()].split()[-1] if line[:m.start()].split() else ""
        if "libdotbench_stubs.a" in line:
            refs[m.group("obj")].add(m.group("sym"))
        elif "internal_stubs.c" in m.group("obj"):
            refs["internal_stubs.c.o"].add(m.group("sym"))
    return refs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("map")
    ap.add_argument("--minus", action="append", default=[])
    ap.add_argument("--json")
    a = ap.parse_args()
    refs = stub_refs(a.map)
    for other in a.minus:
        o = stub_refs(other)
        for k in list(refs):
            refs[k] -= o.get(k, set())
            if not refs[k]:
                del refs[k]
    total = sum(len(v) for v in refs.values())
    for k in sorted(refs):
        print("%s (%d)" % (k.replace(".c.o", ""), len(refs[k])))
        for s in sorted(refs[k]):
            print("    " + s)
    print("total: %d functions in %d groups" % (total, len(refs)), file=sys.stderr)
    if a.json:
        json.dump({k: sorted(v) for k, v in refs.items()}, open(a.json, "w"), indent=1)


if __name__ == "__main__":
    main()
