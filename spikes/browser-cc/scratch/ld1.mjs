import fs from 'node:fs'; import { runLLVM } from '../build/yowasp/package/gen/bundle.js';
import { unpack, toTree } from '../lib/pack.js';
import { linkArgs, runTool, compileCpp } from '../lib/cc-driver.js';
import { inoToCpp } from '../../../tools/dblib/part/ino2cpp.mjs';
import { fieldsHeader } from '../lib/part-glue.mjs';
import path from 'node:path';
const S='../build/site/cc/'; const tree={};
toTree(unpack(new Uint8Array(fs.readFileSync(S+'lib.pack'))),tree); toTree(unpack(new Uint8Array(fs.readFileSync(S+'inc.pack'))),tree);
const dir=process.argv[2]; const m=JSON.parse(fs.readFileSync(dir+'/manifest.json','utf8'));
const files={...tree,'sketch.cpp':inoToCpp(fs.readFileSync(dir+'/src/main.ino','utf8'),'main.ino'),gen:{'dotbench_fields.h':fieldsHeader(m)}};
const cc=await compileCpp(runLLVM,files,{src:'/sketch.cpp',out:'/sketch.o',incs:['/gen']});
console.log(cc.ok, cc.stderr);
const args=linkArgs({objs:['/sketch.o']}); args.splice(1,0,...process.argv.slice(3));
const r=await runTool(runLLVM,args,{...tree,'sketch.o':cc.obj});
console.log(r.ok,r.stderr);
